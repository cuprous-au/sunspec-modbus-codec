/// Renders a `//`-commented block to include at the top of generated Rust sources.
/// Includes clear instructions on how to regenerate the file, and a reference to the specific SunSpec model tag
/// that was the source for generation.
/// `@generated` is the conventional marker various tools (GitHub Linguist, diff/review UIs) look for to treat a file
///  as generated rather than hand-written.
fn generated_file_comment(submodule_tag: &str) -> String {
    [
        "@generated by the sunspec-gen crate (crates/sunspec-gen) from the SunSpec model definitions in"
            .to_string(),
        format!("https://github.com/sunspec/models at tag {submodule_tag}."),
        "Do not edit by hand - run `cargo run -p sunspec-gen` to regenerate.".to_string(),
    ]
    .iter()
    .map(|line| format!("// {line}\n"))
    .collect()
}

fn get_submodule_tag(model_dir: &str) -> String {
    // Cleared because a git hook (this is invoked from lefthook's pre-commit) runs with
    // `GIT_INDEX_FILE`/`GIT_DIR` pointing at the main repository, currently mid-commit.
    // Left in place, that leaks into this `git describe` for the submodule: it still resolves
    // the right tag (repo discovery via `current_dir` isn't affected), but the `--dirty` check
    // diffs the submodule's working tree against the main repo's unrelated index instead of
    // its own, so it comes back dirty even when the submodule genuinely isn't.
    let git_command = || {
        let mut cmd = Command::new("git");
        cmd.current_dir(model_dir)
            .env_remove("GIT_DIR")
            .env_remove("GIT_WORK_TREE")
            .env_remove("GIT_INDEX_FILE")
            .env_remove("GIT_COMMON_DIR")
            .env_remove("GIT_OBJECT_DIRECTORY")
            .env_remove("GIT_ALTERNATE_OBJECT_DIRECTORIES")
            .env_remove("GIT_PREFIX");
        cmd
    };

    git_command()
        .args(["fetch", "--tags"])
        .output()
        .expect("Failed to fetch git submodule tags");

    let output = git_command()
        .args(["describe", "--tags", "--always", "--dirty"])
        .output()
        .expect("Failed to execute `git describe` to get current submodule tag");

    String::from_utf8(output.stdout)
        .expect("Invalid UTF-8 sequence for git submodule tag")
        .lines()
        .next()
        .unwrap_or_default()
        .to_string()
}

fn model_name_from_path(path: &Path) -> &str {
    path.file_prefix()
        .and_then(OsStr::to_str)
        .expect("Failed to convert Sunspec model JSON file name to string")
}

fn collect_models(model_glob: &str) -> Vec<ResolvedModel> {
    let mut vec: Vec<ResolvedModel> = glob(model_glob)
        .expect("Failed to find Sunspec model JSON files by glob pattern")
        .flat_map(|entry| match entry {
            Ok(path) => {
                let json = fs::read_to_string(&path).expect("Failed to read model JSON to string");
                let model: SunspecModel =
                    serde_json::from_str(&json).expect("Failed to parse Sunspec model as JSON");
                let model_name = model_name_from_path(path.as_path());
                Some(resolve_model(&model, model_name.to_string()))
            }
            Err(e) => {
                println!("{:?}", e);
                None
            }
        })
        .collect();

    // Model names are unique by construction (derived from each JSON file's own model number),
    // but are still run through a NameTable for the same reason as points, groups and enums:
    // a genuine collision then fails the build loudly instead of silently generating two
    // colliding items.
    let mut model_names = NameTable::default();
    for model in &vec {
        model_names.register_unique(model.name.clone());
    }
    model_names.deduplicate();

    vec.sort_unstable_by_key(|model| model.model_number);

    vec
}

fn format_and_write(path: &Path, scope: &Scope, submodule_tag: &str) {
    let text_raw = scope.to_string();

    let rustfmt_config: Config = Config {
        edition: Some(Edition::Edition2024),
        ..Default::default()
    };
    let formatted =
        rustfmt_wrapper::rustfmt_config(rustfmt_config, &text_raw).unwrap_or_else(|error| {
            println!(
                "cargo:warning=Error formatting file {}: [{}]. File left unformatted.",
                path.to_str().unwrap_or_default(),
                error
            );
            text_raw
        });

    // Added after formatting, not before: rustfmt is free to reflow this crate's own generated
    // code however it likes, but the notice itself should reach every file byte-for-byte as
    // written here.
    let text = format!("{}\n{formatted}", generated_file_comment(submodule_tag));
    fs::write(path, text).expect("Failed to write generated source to file");
}

pub fn generate() {
    let project_root = env!("CARGO_MANIFEST_DIR");
    let model_dir = format!("{project_root}/models");
    let model_glob = format!("{model_dir}/json/model_*.json");
    let src_path = format!("{project_root}/../sunspec-modbus-lib-rs/src/sunspec");
    let generated_src_dir = Path::new(&src_path);
    let submodule_tag = get_submodule_tag(&model_dir);

    fs::create_dir_all(generated_src_dir.join("models"))
        .expect("Failed to create generated source directories");

    let models = collect_models(&model_glob);

    for model in &models {
        format_and_write(
            &generated_src_dir
                .join("models")
                .join(format!("{}.rs", model.name_snake_case())),
            &generate_model(model),
            &submodule_tag,
        );
    }

    format_and_write(
        &generated_src_dir.join("models.rs"),
        &generate_models_mod(&models),
        &submodule_tag,
    );

    format_and_write(
        &generated_src_dir.join("adapters.rs"),
        &generate_adapters_mod(&models),
        &submodule_tag,
    );
}

/// Regenerates `sunspec-modbus-lib-static`'s mirrored `src/sunspec/models` tree: the C-FFI
/// counterpart - [`Model<id>CallbackAdapter`] and its `StaticModelSpec` dispatch - to each model
/// in `sunspec-modbus-lib-rs`'s `src/sunspec/models`, one file per model, kept out of that crate
/// entirely so a pure-Rust consumer never sees C-FFI types.
pub fn generate_static_models() {
    let project_root = env!("CARGO_MANIFEST_DIR");
    let model_dir = format!("{project_root}/models");
    let model_glob = format!("{model_dir}/json/model_*.json");
    let src_path = format!("{project_root}/../sunspec-modbus-lib-static/src/sunspec");
    let generated_src_dir = Path::new(&src_path);
    let submodule_tag = get_submodule_tag(&model_dir);

    fs::create_dir_all(generated_src_dir.join("models"))
        .expect("Failed to create generated source directories");

    let models = collect_models(&model_glob);

    for model in &models {
        if let Some(scope) = generate_static_model(model) {
            format_and_write(
                &generated_src_dir
                    .join("models")
                    .join(format!("{}.rs", model.name_snake_case())),
                &scope,
                &submodule_tag,
            );
        }
    }

    format_and_write(
        &generated_src_dir.join("models.rs"),
        &generate_static_models_mod(&models),
        &submodule_tag,
    );
}

/// Regenerates `sunspec-modbus-derive`'s model writability registry (`src/model_registry.rs`):
/// the one piece of per-model knowledge the `#[derive(ModelList)]` macro can't get from the
/// annotated struct's own tokens - which models have any writable points at all, and so need a
/// slot in the generated `WriteAdapters` struct. Keyed by each model's generated module name
/// (`model_<id>`, already unique) rather than its model number, since that's exactly what the
/// macro can read straight off a field's type path.
pub fn generate_model_registry() {
    let project_root = env!("CARGO_MANIFEST_DIR");
    let model_dir = format!("{project_root}/models");
    let model_glob = format!("{model_dir}/json/model_*.json");
    let submodule_tag = get_submodule_tag(&model_dir);

    let output_path =
        Path::new(project_root).join("../sunspec-modbus-derive/src/model_registry.rs");

    let models = collect_models(&model_glob);
    format_and_write(
        &output_path,
        &generate_model_registry_source(&models),
        &submodule_tag,
    );
}

/// The `WRITABLE_MODELS` table itself - see [`generate_model_registry`].
fn generate_model_registry_source(models: &[ResolvedModel]) -> Scope {
    let mut scope = Scope::new();
    let entries: Vec<String> = models
        .iter()
        .filter(|model| model_is_writable(model))
        .map(|model| format!("\"{}\"", model_feature_name(model)))
        .collect();

    scope.raw(format!(
        "/// SunSpec model modules - named after their generated module, e.g. `model_1` - that\n\
         /// have at least one writable point. `#[derive(ModelList)]` uses this to decide whether\n\
         /// a field's model needs a slot in the generated `WriteAdapters` struct.\n\
         pub static WRITABLE_MODELS: &[&str] = &[{}];\n",
        entries.join(", ")
    ));

    scope
}

/// Replaces the text between a `{marker_prefix} @generated:start` / `{marker_prefix}
/// @generated:end` marker pair in `path` with `content`, leaving everything else in the file
/// untouched. Used to keep the per-model feature/define lists in `Cargo.toml`/`cbindgen.toml`
/// in sync with the actual model set without needing to own the whole file, which also carries
/// hand-maintained content - dependencies, package metadata, other cbindgen settings.
fn replace_generated_region(path: &Path, marker_prefix: &str, content: &str) {
    let existing =
        fs::read_to_string(path).unwrap_or_else(|error| panic!("failed to read {path:?}: {error}"));

    let start_marker = format!("{marker_prefix} @generated:start");
    let end_marker = format!("{marker_prefix} @generated:end");

    let start = existing
        .find(&start_marker)
        .unwrap_or_else(|| panic!("{path:?} is missing `{start_marker}`"));
    let end = existing
        .find(&end_marker)
        .unwrap_or_else(|| panic!("{path:?} is missing `{end_marker}`"));
    assert!(
        start < end,
        "{path:?}: `{start_marker}` must appear before `{end_marker}`"
    );

    let before = &existing[..start + start_marker.len()];
    let after = &existing[end..];
    fs::write(path, format!("{before}\n{content}\n{after}"))
        .unwrap_or_else(|error| panic!("failed to write {path:?}: {error}"));
}

/// Renders the `[features]` block managed in a crate's `Cargo.toml`: one `model_<id> = [...]`
/// entry per model - forwarding to the same feature on each of `forward_to` too, for a crate
/// that depends on `sunspec-modbus-lib-rs` rather than generating that model's code itself -
/// plus an `all-models` feature aggregating every one of them, so `default` only needs to name
/// that instead of carrying the whole list.
fn render_cargo_features(models: &[ResolvedModel], forward_to: &[&str]) -> String {
    let mut out = String::from("all-models = [\n");
    for model in models {
        out.push_str(&format!("    \"{}\",\n", model_feature_name(model)));
    }
    out.push_str("]\n");

    for model in models {
        let name = model_feature_name(model);
        let deps: Vec<String> = forward_to
            .iter()
            .map(|dep| format!("\"{dep}/{name}\""))
            .collect();
        out.push_str(&format!("{name} = [{}]\n", deps.join(", ")));
    }
    out
}

/// Renders the `[defines]` block managed in `sunspec-modbus-lib-static`'s `cbindgen.toml`: one
/// entry per model, mapping its Cargo feature to the C preprocessor guard cbindgen wraps that
/// model's declarations in - see [`model_cfg_attribute`].
fn render_cbindgen_defines(models: &[ResolvedModel]) -> String {
    let mut out = String::new();
    for model in models {
        out.push_str(&format!(
            "\"feature = {}\" = \"SUNSPEC_MODEL_{}_ENABLED\"\n",
            model_feature_name(model),
            model.model_number
        ));
    }
    out
}

/// Renders the body of the `after_includes` block managed in `sunspec-modbus-lib-static`'s
/// `cbindgen.toml`: a `#ifndef`/`#define`/`#endif` block for required model 1, matching the Rust
/// side's default feature. `SUNSPEC_NO_DEFAULT_MODELS` suppresses that declaration for static
/// library builds that intentionally disable the default feature. C callers define
/// `SUNSPEC_MODEL_<id>_ENABLED` themselves for every additional linked model.
fn render_cbindgen_default_models(models: &[ResolvedModel]) -> String {
    let model_1 = models
        .iter()
        .find(|model| model.model_number == 1)
        .expect("SunSpec model 1 must exist");
    let define = format!("SUNSPEC_MODEL_{}_ENABLED", model_1.model_number);
    format!(
        "#if !defined(SUNSPEC_NO_DEFAULT_MODELS)\n#ifndef {define}\n#define {define}\n#endif\n\
         #endif // !defined(SUNSPEC_NO_DEFAULT_MODELS)\n"
    )
}

/// Regenerates the per-model `[features]` block in `sunspec-modbus-lib-rs`'s and
/// `sunspec-modbus-lib-static`'s `Cargo.toml`, and the matching `[defines]`/`after_includes`
/// blocks in `sunspec-modbus-lib-static`'s `cbindgen.toml` (see `replace_generated_region`), so
/// each model's generated code - and, in the C header, its declarations - can be compiled in or
/// out independently. Required model 1 is the sole default in each crate and in the C header;
/// `SUNSPEC_NO_DEFAULT_MODELS` lets C callers suppress its declaration for no-default-feature
/// static-library builds. Consumers enable every other model explicitly.
pub fn generate_model_features() {
    let project_root = env!("CARGO_MANIFEST_DIR");
    let model_glob = format!("{project_root}/models/json/model_*.json");
    let models = collect_models(&model_glob);

    replace_generated_region(
        &Path::new(project_root).join("../sunspec-modbus-lib-rs/Cargo.toml"),
        "#",
        &render_cargo_features(&models, &[]),
    );
    replace_generated_region(
        &Path::new(project_root).join("../sunspec-modbus-lib-static/Cargo.toml"),
        "#",
        &render_cargo_features(&models, &["sunspec-modbus-lib-rs"]),
    );
    let cbindgen_toml = Path::new(project_root).join("../sunspec-modbus-lib-static/cbindgen.toml");
    replace_generated_region(&cbindgen_toml, "#", &render_cbindgen_defines(&models));
    replace_generated_region(
        &cbindgen_toml,
        "//",
        &render_cbindgen_default_models(&models),
    );
}
